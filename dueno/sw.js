// Service worker del panel del dueño: permite instalarlo como app en el celular.
// Siempre busca la versión nueva en la red; lo guardado solo se usa si no hay conexión.
const CACHE = 'dueno-v1';
const FILES = ['./', './index.html', './manifest.json', './icon-192.png', './icon-512.png'];

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('dueno-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const url = new URL(e.request.url);
  const enPanel = FILES.some(f => url.pathname === new URL(f, self.registration.scope).pathname);
  if (e.request.method !== 'GET' || url.origin !== location.origin || !enPanel) return;
  e.respondWith(fetch(e.request).then(r => {
    const copy = r.clone();
    caches.open(CACHE).then(c => c.put(e.request, copy));
    return r;
  }).catch(() => caches.match(e.request)));
});
